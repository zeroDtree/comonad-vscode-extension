import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as cordis from 'cordis';
import * as schemastery from 'schemastery';
import * as vscode from 'vscode';

/**
 * The modules Comonad lends a plugin of yours.
 *
 * A plugin installed in the library (`~/.comonad/plugins/…`) is loaded from its own folder, so a
 * `require('cordis')` inside it looks for a `node_modules` of its own and finds none. Comonad writes
 * one above the library, and Node finds it by walking up from wherever the plugin sits.
 *
 * The files are bridges into this process, written the way the harness compatibility shims are, so a
 * plugin shares the host's classes — one cordis, one `Service`, one `vscode` — instead of carrying a
 * second copy that would not know the host's contexts.
 */

/** Where the generated modules read their values from: one bridge for the whole process. */
const BRIDGE = Symbol.for('comonad.plugin.bindings');

/** The names a plugin may require and be handed the host's own module for. */
const LENT = ['cordis', 'schemastery', 'vscode'] as const;

/** What the lent names mean here, as a plugin's `require` sees them. */
function bindings(): Record<string, unknown> {
	return { cordis, schemastery, vscode };
}

/** Puts the values in place: a plugin's module is read long after this, from a file that only reads them. */
export function bindModuleShims(): void {
	(globalThis as Record<symbol, unknown>)[BRIDGE] = bindings();
}

/** `default` and friends cannot be declared as a binding, and a module may still export them. */
function declarable(name: string): boolean {
	return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) && !['default', 'class', 'function', 'import', 'export', 'new', 'delete', 'in', 'with', 'void', 'typeof'].includes(name);
}

/**
 * Writes the lent modules under `<library>/node_modules`, and answers the names it wrote. Written
 * again at every start: the files are tiny, and a half-installed one is worse than a slow one.
 */
export function writeModuleShims(library: string): string[] {
	const bridge = bindings();
	(globalThis as Record<symbol, unknown>)[BRIDGE] = bridge;
	const root = join(library, 'node_modules');
	const written: string[] = [];
	for (const name of LENT) {
		const exports = bridge[name] as Record<string, unknown>;
		const folder = join(root, name);
		mkdirSync(folder, { recursive: true });
		writeFileSync(
			join(folder, 'package.json'),
			`${JSON.stringify({ name, version: '0.0.0', private: true, main: './index.cjs', exports: { '.': { require: './index.cjs', import: './index.mjs' } } }, null, '\t')}\n`,
		);
		const header = `// Generated by Comonad: the host's own ${name} (see src/services/plugin-modules.ts).\n// Written again whenever Comonad starts; safe to delete.\n`;
		const lookup = `const values = (globalThis[Symbol.for('comonad.plugin.bindings')] ?? {})[${JSON.stringify(name)}] ?? {};\n`;
		writeFileSync(join(folder, 'index.cjs'), `${header}${lookup}module.exports = values;\n`);
		writeFileSync(
			join(folder, 'index.mjs'),
			[
				header,
				lookup,
				...Object.keys(exports)
					.filter(declarable)
					.map((key) => `export const ${key} = values[${JSON.stringify(key)}];`),
				'export default values;',
				'',
			].join('\n'),
		);
		written.push(name);
	}
	return written;
}
